#!/usr/bin/env bash
# gen-ref.sh -- render the Faust references of the alogos plugin into
# tests/ref/alogos_ref.h. Run by hand when the spec changes; the tests
# read the committed header and need no faust binary.
#
# FAUSTLIBS: faustlibraries clone
# SEAMLIBS:  faust-libraries/src (seam.silvi.lib; h/nextprime.h for sff.np)
# WINSECONDS: length of every window (default 16; 18 windows keep the header
#            below 16 MB)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
FAUSTLIBS="${FAUSTLIBS:-/Users/giuseppe/Documents/github/grame/faustlibraries}"
SEAMLIBS="${SEAMLIBS:-$(cd "$ROOT/../faust-libraries/src" && pwd)}"
SECONDS_WIN="${WINSECONDS:-16}"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
OUT="$ROOT/tests/ref/alogos_ref.h"
mkdir -p "$(dirname "$OUT")"

build() { # dsp file in dsp/ or in $WORK
    local src="$HERE/dsp/$1"; [ -f "$WORK/$1" ] && src="$WORK/$1"
    faust -I "$FAUSTLIBS" -I "$SEAMLIBS" -double -lang cpp -cn Ref "$src" -o "$WORK/ref.h"
    c++ -std=c++17 -O2 -I "$WORK" -I "$SEAMLIBS/h" -I "$ROOT/tests" "$HERE/refdump.cpp" -o "$WORK/refdump"
}

# The windows: scale tag, Faust r, D, Faust g, N list. id 1, j snapped at 3.33 m.
WINDOWS=(
    "phi   sma.phi(1) 1 sma.rphi(1)  1,4,17"
    "phi   sma.phi(1) 4 sma.rphi(1)  4,40"
    "pi    ma.PI      1 1/ma.PI      4,8"
    "sqrt2 sqrt(2)    2 1/sqrt(2)    4,30"
)

{
    echo "// GENERATED by doc/study/alogos/gen-ref.sh -- do not edit."
    echo "// $(faust --version | head -1); faustlibraries $(git -C "$FAUSTLIBS" rev-parse --short HEAD);"
    echo "// faust-libraries $(git -C "$SEAMLIBS" rev-parse --short HEAD)."
    echo "//"
    echo "// Indices: scale 0..3 = phi, sqrt 2, e, pi; density 0..2 = D 1, 2, 4;"
    echo "// id 0..4; j 0..81 (slots above J(r, D) are 0)."
    echo "// N_max: the largest N >= 1 with d * pow(r, (N - 1 + 3/4)/D) / c <= 90 s,"
    echo "// capped at 128, d = kAlgrid, c = 343.21462268256795."
    echo "// Delay list of a setting: 4 * N_max values sgs.aldel(r, D, d, i, k), k-major:"
    echo "// face 0 sections 0..N_max-1, then face 1, 2, 3."
    echo "// kAldelHash: 64-bit FNV-1a (offset 0xcbf29ce484222325, prime 0x100000001b3)"
    echo "// over that list, each value as 4 bytes uint32 little-endian:"
    echo "//   h = offset; for each value v, for b in 0..3: h ^= (v >> 8b) & 0xff; h *= prime."
    echo "// kAldelEdge: the lists at j = 0 (side 0) and j = J (side 1), concatenated;"
    echo "// list [s][dn][id][side] starts at kAldelEdgeOff, has 4 * kAldelEdgeNmax"
    echo "// values, value (k, i) at offset + k * N_max + i."
    echo "// kWin<rate>_<scale>_D<D>_N<N>: sgs.alogos(r, D, g, N, 1, kWinJ_<scale>_D<D>)"
    echo "// on the burst (tests/stunedrev_burst.h), blocks of 256, $SECONDS_WIN s;"
    echo "// [face][second][first 512 samples], _energy[face][second]."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "namespace alogosref {"
    build aldel.dsp
    "$WORK/refdump" grid 96000
    "$WORK/refdump" aldel 48000 48
    "$WORK/refdump" aldel 96000 96
    for w in "${WINDOWS[@]}"; do
        read -r tag rexp D gexp ns <<< "$w"
        j="$("$WORK/refdump" winj "$tag" "$D")"
        echo "// kWinJ_${tag}_D$D: round(4 D log_r(3.33)) clamped to 0..J, id 1; g = $gexp."
        echo "constexpr int kWinJ_${tag}_D$D = $j;"
        for n in ${ns//,/ }; do
            sed -e "s|^r = .*;|r = $rexp;|" -e "s|^D = .*;|D = $D;|" -e "s|^g = .*;|g = $gexp;|" \
                -e "s|^N = .*;|N = $n;|" -e "s|^id = .*;|id = 1;|" -e "s|^j = .*;|j = $j;|" \
                "$HERE/dsp/alogos.dsp" > "$WORK/alogos.dsp"
            build alogos.dsp
            "$WORK/refdump" windows 96000 "$SECONDS_WIN" "kWin96_${tag}_D${D}_N$n"
            "$WORK/refdump" windows 48000 "$SECONDS_WIN" "kWin48_${tag}_D${D}_N$n"
            rm "$WORK/alogos.dsp"
        done
    done
    echo "} // namespace alogosref"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
