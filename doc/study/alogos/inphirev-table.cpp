// inphirev-table.cpp -- writes INPHIREV's delay table, for every stone id,
// grid point, section k and index i, at 44.1/48/96/192 kHz, as the header
// tests/ref/alogos_inphirev_table.h.  ALOGOS's default must reproduce this
// table exactly; the header is the fixture that proves it.
// This generator builds only at commits before INPHIREV's removal from the
// tree (a later task deletes plugins/inphirev).  From this directory:
// c++ -std=c++17 -O2 -I ../../../plugins/inphirev/source -I ../../../plugins/_common inphirev-table.cpp -o inphirev-table && ./inphirev-table > ../../../tests/ref/alogos_inphirev_table.h
#include "inphirev_dsp.h"
#include <cstdio>

using namespace inphirev;

int main() {
    std::printf("// GENERATED by doc/study/alogos/inphirev-table.cpp -- do not edit.\n");
    std::printf("// INPHIREV's delay table: [stone id][grid j][section k][index i].\n");
    std::printf("#pragma once\n#include <cstdint>\n\nnamespace alogosref {\n");
    const struct { const char* name; double fs; } rates[] = {
        {"kInphirev44", 44100.0}, {"kInphirev48", 48000.0},
        {"kInphirev96", 96000.0}, {"kInphirev192", 192000.0}};
    for (const auto& r : rates) {
        const Seam::PrimeSieve sieve(sieveBound(r.fs));
        std::printf("\nconstexpr uint32_t %s[9][15][4][18] = {\n", r.name);
        for (int id = 0; id < 9; ++id) {
            std::printf("{\n");
            for (int j = 0; j < 15; ++j) {
                std::printf("{");
                for (int k = 0; k < 4; ++k) {
                    std::printf("{");
                    for (int i = 0; i < 18; ++i)
                        std::printf("%u%s", sectionDelay(gridMetres(id, j), i, k, r.fs, sieve), i < 17 ? "," : "");
                    std::printf("}%s", k < 3 ? "," : "");
                }
                std::printf("}%s\n", j < 14 ? "," : "");
            }
            std::printf("}%s\n", id < 8 ? "," : "");
        }
        std::printf("};\n");
    }
    std::printf("\n}  // namespace alogosref\n");
}
