#!/usr/bin/env bash
# gen-ref.sh -- render the Faust references of the inphirev plugin into
# tests/ref/inphirev_ref.h. Run by hand when the spec changes; the tests
# read the committed header and need no faust binary.
#
# FAUSTLIBS: faustlibraries clone
# SEAMLIBS:  faust-libraries/src (seam.silvi.lib; h/nextprime.h for sff.np)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
FAUSTLIBS="${FAUSTLIBS:-/Users/giuseppe/Documents/github/grame/faustlibraries}"
SEAMLIBS="${SEAMLIBS:-$(cd "$ROOT/../faust-libraries/src" && pwd)}"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
OUT="$ROOT/tests/ref/inphirev_ref.h"
mkdir -p "$(dirname "$OUT")"

build() { # dsp file in dsp/ or in $WORK
    local src="$HERE/dsp/$1"; [ -f "$WORK/$1" ] && src="$WORK/$1"
    faust -I "$FAUSTLIBS" -I "$SEAMLIBS" -double -lang cpp -cn Ref "$src" -o "$WORK/ref.h"
    c++ -std=c++17 -O2 -I "$WORK" -I "$SEAMLIBS/h" -I "$ROOT/tests" "$HERE/refdump.cpp" -o "$WORK/refdump"
}

{
    echo "// GENERATED by doc/study/inphirev/gen-ref.sh -- do not edit."
    echo "// $(faust --version | head -1); faustlibraries $(git -C "$FAUSTLIBS" rev-parse --short HEAD);"
    echo "// faust-libraries $(git -C "$SEAMLIBS" rev-parse --short HEAD)."
    echo "#pragma once"
    echo "namespace inphirevref {"
    build tsos.dsp
    "$WORK/refdump" tsos 44100 kTsos20
    build ipdel.dsp
    for sr in 44100:44 48000:48 96000:96 192000:192; do "$WORK/refdump" ipdel ${sr%%:*} kDel${sr##*:}; done
    for n in 1 4 17; do
        sed "s/^N = 4;/N = $n;/" "$HERE/dsp/inphirev.dsp" > "$WORK/inphirev.dsp"
        build inphirev.dsp
        "$WORK/refdump" windows 96000 30 kWin96_N$n
        "$WORK/refdump" windows 48000 30 kWin48_N$n
        rm "$WORK/inphirev.dsp"
    done
    echo "} // namespace inphirevref"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
